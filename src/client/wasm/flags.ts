/**
 * Compiler argv assembly for the WebAssembly target.
 *
 * The browser toolchain exposes driver-less clang: we invoke `clang -cc1`
 * directly and link with `wasm-ld`. That is the same pipeline the toolchain
 * presets use, kept in our own code so the IDE controls the standard, the
 * optimisation level, the include search path and the memory ceiling.
 *
 * Invoking `-cc1` also means driver-only switches (`-pthread`, `-fsanitize=…`,
 * `-lm`, `-Wall`) are not available. See docs/wasm-client-only-feasibility.md
 * §2.4: threading needs SharedArrayBuffer, sanitizers need extra bundles, and
 * libm lives inside libc. The flag whitelist below reflects that.
 */
import type { OptId, StdId } from '../../shared/types';
import { t } from '../i18n';
import { WORKSPACE_ROOT } from './constants';

const MAX_EXTRA_FLAGS = 8;
const MAX_FLAG_LENGTH = 160;
const MAX_FLAGS_BYTES = 800;

/** Flags accepted verbatim. Warning groups are driver-only and stay out. */
const EXACT_FLAGS = new Set<string>(['-DNDEBUG', '-DDEBUG']);

const DEFINE_RE = /^([A-Za-z_][A-Za-z0-9_]*)(?:=(.+))?$/;
const DEFINE_VALUE_RE = /^[A-Za-z0-9_.,:+\-*/%<>=!&|^~"'()[\]]+$/;

export class FlagError extends Error {
  constructor(public readonly flag: string, message: string) {
    super(message);
    this.name = 'FlagError';
  }
}

/**
 * Compiler argv is an execution surface, not a string to forward. Every
 * element is either generated by us or matched against this narrow allowlist.
 */
export function sanitizeExtraFlags(raw: unknown): string[] {
  if (raw === undefined || raw === null) return [];
  if (!Array.isArray(raw)) throw new FlagError('', t('app.error.flagsInvalid'));
  if (raw.length > MAX_EXTRA_FLAGS) {
    throw new FlagError('', t('app.error.flagsTooMany', { max: MAX_EXTRA_FLAGS }));
  }

  const result: string[] = [];
  let total = 0;

  for (const item of raw) {
    if (typeof item !== 'string') throw new FlagError('', t('app.error.flagsInvalid'));
    const flag = item.trim();
    if (!flag || flag.length > MAX_FLAG_LENGTH) throw new FlagError(flag, t('app.error.flagInvalid', { flag }));
    if (/[\0\r\n]/.test(flag)) throw new FlagError(flag, t('app.error.flagInvalid', { flag }));
    total += new TextEncoder().encode(flag).length;
    if (total > MAX_FLAGS_BYTES) throw new FlagError('', t('app.error.flagsTooMany', { max: MAX_EXTRA_FLAGS }));

    if (EXACT_FLAGS.has(flag)) {
      result.push(flag);
      continue;
    }
    if (flag.startsWith('-D')) {
      result.push(validateDefine(flag));
      continue;
    }
    if (flag.startsWith('-I')) {
      result.push(validateIncludePath(flag));
      continue;
    }
    // Silently accepted no-ops: libm is part of libc in this target.
    if (flag === '-lm') continue;
    throw new FlagError(flag, t('app.error.flagNotAllowed', { flag }));
  }

  return dedupe(result);
}

function dedupe(flags: string[]): string[] {
  return [...new Set(flags)];
}

function validateDefine(flag: string): string {
  const body = flag.slice(2);
  const match = DEFINE_RE.exec(body);
  if (!match) throw new FlagError(flag, t('app.error.flagNotAllowed', { flag }));
  const value = match[2];
  if (value !== undefined && !DEFINE_VALUE_RE.test(value)) {
    throw new FlagError(flag, t('app.error.flagNotAllowed', { flag }));
  }
  return flag;
}

function validateIncludePath(flag: string): string {
  const raw = flag.slice(2);
  if (!raw || raw.startsWith('/') || raw.includes('..') || raw.includes('\\')) {
    throw new FlagError(flag, t('app.error.includeOutsideWorkspace', { dir: raw }));
  }
  const parts = raw.split('/').filter((part) => part !== '' && part !== '.');
  const normalized = parts.join('/');
  if (!normalized) return `-I${WORKSPACE_ROOT}`;
  if (!/^[A-Za-z0-9_][A-Za-z0-9_.\-/]*$/.test(normalized)) {
    throw new FlagError(flag, t('app.error.includeNameInvalid', { dir: raw }));
  }
  return `-I${WORKSPACE_ROOT}/${normalized}`;
}

/**
 * Common clang frontend flags; the sysroot layout comes from the toolchain.
 *
 * `-cc1` only accepts cc1 options, not driver options: `-fdiagnostics-format`
 * and `-fno-color-diagnostics` are rejected outright, and `-ferror-limit` must
 * be passed as a separate value. Diagnostics are plain text anyway — a wasm
 * process has no TTY to colour.
 */
const CC1_FRONTEND = [
  '-cc1',
  '-triple',
  'wasm32-unknown-emscripten',
  '-emit-obj',
  '-disable-free',
  '-clear-ast-before-backend',
  '-disable-llvm-verifier',
  '-discard-value-names',
  '-mrelocation-model',
  'static',
  '-mframe-pointer=none',
  '-ffp-contract=on',
  '-fno-rounding-math',
  '-mconstructor-aliases',
  '-target-cpu',
  'generic',
  '-fvisibility=hidden',
];

/**
 * C++ include search path. libc++ headers must precede /usr/include so that
 * <cctype> resolves to libc++'s shim rather than the C header directly.
 */
const CC1_CPP_INCLUDES = [
  '-internal-isystem',
  '/usr/include/c++/v1',
  '-internal-isystem',
  '/usr/include/compat',
  '-internal-isystem',
  '/usr/lib/clang/23/include',
  '-resource-dir',
  '/usr/lib/clang/23',
  '-internal-isystem',
  '/usr/include',
];

/**
 * Trailing cc1 flags. `-ferror-limit` caps how many diagnostics come back from
 * one translation unit so a broken paste cannot flood the panel.
 */
const CC1_TAIL = ['-fdeprecated-macro', '-ferror-limit', '50', '-fgnuc-version=4.2.1', '-fcxx-exceptions', '-fexceptions'];

/** wasm-ld base line: WASI command module with an emscripten-style libc. */
const WASM_LD_BASE = [
  '-L/usr/lib/emscripten/cache-lib/wasm32-emscripten',
  '--entry=main',
  '--export=main',
  '--import-undefined',
  '--allow-undefined',
  '--export-table',
  '--table-base=1',
  '--export=__wasm_call_ctors',
];

const WASM_LD_CPP_LIBS = [
  '-lc++-noexcept',
  '-lc++abi-noexcept',
  '-lc',
  '-ldlmalloc',
  '-lcompiler_rt',
  '-lsockets',
];

/** Default wasm stack; sized so recursion-heavy algorithms do not trap. */
const STACK_SIZE_BYTES = 1024 * 1024;
/** Initial linear memory. The module grows up to the configured ceiling. */
const INITIAL_MEMORY_BYTES = 16 * 1024 * 1024;

export interface CompileArgOptions {
  std: StdId;
  opt: OptId;
  extraFlags: string[];
  sourcePath: string;
  objectPath: string;
}

/**
 * `clang -cc1 …` argv for one translation unit. The returned array starts with
 * `argv[0]` because the toolchain worker expects the full command line.
 */
export function compileArgv(options: CompileArgOptions): string[] {
  return [
    'clang',
    ...CC1_FRONTEND,
    options.opt,
    ...CC1_CPP_INCLUDES,
    `-std=${options.std}`,
    // User include paths are already normalised to absolute VFS paths.
    `-I${WORKSPACE_ROOT}`,
    ...options.extraFlags,
    ...CC1_TAIL,
    '-main-file-name',
    basename(options.sourcePath),
    '-o',
    options.objectPath,
    '-x',
    'c++',
    options.sourcePath,
  ];
}

/**
 * `wasm-ld` argv. `--initial-memory`/`--max-memory` bake the memory ceiling
 * into the module, so a runaway allocation fails inside the wasm sandbox
 * instead of growing until the browser tab dies.
 */
export function linkArgv(objects: string[], outputPath: string, memoryLimitMb: number): string[] {
  const maxMemory = Math.max(1, memoryLimitMb) * 1024 * 1024;
  const initialMemory = Math.min(INITIAL_MEMORY_BYTES, maxMemory);
  return [
    'wasm-ld',
    ...objects,
    '-o',
    outputPath,
    ...WASM_LD_BASE,
    ...WASM_LD_CPP_LIBS,
    `--initial-memory=${initialMemory}`,
    `--max-memory=${maxMemory}`,
    '-z',
    `stack-size=${STACK_SIZE_BYTES}`,
  ];
}

export function basename(path: string): string {
  const index = path.lastIndexOf('/');
  return index < 0 ? path : path.slice(index + 1);
}

export function dirname(path: string): string {
  const index = path.lastIndexOf('/');
  return index <= 0 ? WORKSPACE_ROOT : path.slice(0, index);
}
